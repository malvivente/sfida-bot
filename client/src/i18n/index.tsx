interface LanguageContextType {
  language: Language;
  setLanguage: (lang: Language) => void;
  toggleLanguage: () => void;
  t: (key: string, params?: Record<string, string | number>) => string;
}

const LanguageContext = createContext<LanguageContextType>({
  language: 'en',
  setLanguage: () => {},
  toggleLanguage: () => {},
  t: (key) => key,
});

export const LanguageProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [language, setLanguageState] = useState<Language>(() => {
    try {
      const saved = localStorage.getItem('sfidabot_language');
      if (saved === 'it' || saved === 'en') return saved;
      const tg = (typeof window !== 'undefined' ? (window as any).Telegram?.WebApp : null);
      const tgLang = tg?.initDataUnsafe?.user?.language_code;
      if (tgLang && typeof tgLang === 'string' && tgLang.toLowerCase().startsWith('it')) {
        return 'it';
      }
      const navLang = typeof navigator !== 'undefined' ? navigator.language : '';
      if (navLang && navLang.toLowerCase().startsWith('it')) {
        return 'it';
      }
      return 'en';
    } catch {
      return 'en';
    }
  });

  const setLanguage = (lang: Language) => {
    setLanguageState(lang);
    try {
      localStorage.setItem('sfidabot_language', lang);
    } catch {}
  };

  const toggleLanguage = () => {
    const nextLang: Language = language === 'en' ? 'it' : 'en';
    setLanguage(nextLang);
  };

  const t = (key: string, params?: Record<string, string | number>): string => {
    const entry = translations[key];
    let text = entry ? (entry[language] || entry.en || key) : key;
    if (params) {
      for (const [paramKey, paramVal] of Object.entries(params)) {
        text = text.replace(new RegExp(`\\{${paramKey}\\}`, 'g'), String(paramVal));
      }
    }
    return text;
  };

  return (
    <LanguageContext.Provider value={{ language, setLanguage, toggleLanguage, t }}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useI18n = () => useContext(LanguageContext);
export const useLanguage = useI18n;
